// `{detail}` is an optional provider message appended with the language's separator.
const DETAIL_SEP = { zh: '：', en: ': ' };

export function reqLang(req) {
  return String(req?.headers?.['x-ui-lang'] || '').toLowerCase() === 'en' ? 'en' : 'zh';
}

export function tr(lang, key, params = {}) {
  const table = MESSAGES[lang] || MESSAGES.zh;
  const template = table[key] ?? MESSAGES.zh[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, k) => {
    const v = params?.[k];
    if (k === 'detail') return v ? `${DETAIL_SEP[lang] || DETAIL_SEP.zh}${String(v).slice(0, 300)}` : '';
    return v == null ? '' : String(v);
  });
}
