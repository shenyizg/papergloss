function detect() {
  try {
    const saved = JSON.parse(localStorage.getItem('pr.lang') || 'null');
    if (saved === 'zh' || saved === 'en') return saved;
  } catch {
    // storage unavailable: fall back to the browser language
  }
  return /^zh\b/i.test(navigator.language || '') ? 'zh' : 'en';
}

let lang = detect();
document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';

export function getLang() {
  return lang;
}

export function setLang(next) {
  if (next !== 'zh' && next !== 'en') return;
  lang = next;
  document.documentElement.lang = next === 'zh' ? 'zh-CN' : 'en';
  try {
    localStorage.setItem('pr.lang', JSON.stringify(next));
  } catch {
    // the choice just won't persist
  }
}

export function t(key, params) {
  let s = DICT[lang][key] ?? DICT.zh[key] ?? key;
  if (params) s = s.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? ''));
  return s;
}

// Where a quote came from, for display.
export function formatLocation(loc) {
  if (!loc) return '';
  if (loc.page) return t('reader.page', { n: loc.page });
  if (loc.kind === 'html') return loc.section || loc.label || t('loc.body');
  return loc.label || '';
}
